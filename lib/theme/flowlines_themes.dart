import 'package:flutter/material.dart';

/// Theme, pipe-style catalog for Flow Lines.
///
/// Every theme stays inside the workshop material world: real woods, routed
/// boards, brass/copper/steel trim, enamel pipe colors. No neon, no
/// cyberpunk, no generic Material look. Variety comes from different woods,
/// metal accents and enamel pipe palettes.
class FlowThemeDef {
  final String id;
  final String name;
  final Color bgDeep;
  final Color bgMid;
  final Color boardDark;
  final Color boardLight;
  final Color groove;
  final Color accent;
  final Color accentLight;
  final Color accentDark;
  final Color text;
  final Color textDim;
  final List<Color> pipeColors;
  final List<String> pipeColorNames;

  const FlowThemeDef({
    required this.id,
    required this.name,
    required this.bgDeep,
    required this.bgMid,
    required this.boardDark,
    required this.boardLight,
    required this.groove,
    required this.accent,
    required this.accentLight,
    required this.accentDark,
    required this.text,
    required this.textDim,
    required this.pipeColors,
    required this.pipeColorNames,
  });
}

